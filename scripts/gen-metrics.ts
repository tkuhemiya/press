// Measures the bundled fonts in Chromium and writes src/text/metrics.ts: the advance of every
// character Press expects in labels, in thousandths of an em. Run after changing a font.
//   node scripts/gen-metrics.ts
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const { chromium } = require('playwright');

const root = new URL('../', import.meta.url);
const font = (file: string) => readFileSync(new URL(`assets/fonts/${file}`, root)).toString('base64');

const faces = {
  sans400: ['Inter', 400, 'inter-latin-400-normal.woff2'],
  sans500: ['Inter', 500, 'inter-latin-500-normal.woff2'],
  sans600: ['Inter', 600, 'inter-latin-600-normal.woff2'],
  mono400: ['JetBrains Mono', 400, 'jetbrains-mono-latin-400-normal.woff2'],
} as const;

// Printable ASCII, then the punctuation and symbols that turn up in explanations.
const extra = '–—…‘’“”•·→←↔×÷±≤≥≠°';
const chars: string[] = [];
for (let c = 32; c < 127; c++) chars.push(String.fromCharCode(c));
chars.push(...extra);

const css = Object.values(faces)
  .map(([family, weight, file]) => `@font-face{font-family:"${family}";font-weight:${weight};src:url(data:font/woff2;base64,${font(file)}) format("woff2")}`)
  .join('\n');

const browser = await chromium.launch();
const page = await browser.newPage();
await page.setContent(`<style>${css}</style><body>${Object.values(faces).map(([f, w]) => `<span style="font:${w} 20px '${f}'">x</span>`).join('')}</body>`);
await page.evaluate(() => document.fonts.ready);

const tables: Record<string, number[]> = {};
for (const [name, [family, weight]] of Object.entries(faces)) {
  tables[name] = await page.evaluate(
    ({ family, weight, chars }: { family: string; weight: number; chars: string[] }) => {
      const ctx = document.createElement('canvas').getContext('2d')!;
      ctx.font = `${weight} 1000px "${family}"`;
      return chars.map((ch: string) => Math.round(ctx.measureText(ch).width));
    },
    { family, weight, chars }
  );
}
await browser.close();

let out = '// Generated by scripts/gen-metrics.ts. Do not edit.\n';
out += '// Advances in thousandths of an em for each character in CHARS.\n\n';
out += `export const CHARS = ${JSON.stringify(chars.join(''))};\n\n`;
out += 'export const ADVANCES: Record<string, number[]> = {\n';
for (const [name, t] of Object.entries(tables)) out += `  ${name}: [${t.join(', ')}],\n`;
out += '};\n';
writeFileSync(new URL('src/text/metrics.ts', root), out);
console.log('wrote src/text/metrics.ts');
